    def test_inspection_finishing_after_job_start_cannot_replace_plan(self):
        h = self.fixture("acquisition"); payload = h.approve(); h.mode = "wait"
        entered, release = threading.Event(), threading.Event()
        original = h.manager.services.fetch_snapshot
        def blocked(*args):
            entered.set(); release.wait(3); return original(*args)
        h.manager.services = replace(h.manager.services, fetch_snapshot=blocked)
        failures = []
        def inspect():
            try: h.manager.inspect({"repoId":"fixture/Another", "revision":"main"})
            except Exception as error: failures.append(error)
        thread = threading.Thread(target=inspect)
        try:
            thread.start(); self.assertTrue(entered.wait(2)); h.start(payload)
            self.wait_for(lambda:h.manager.process is not None)
            release.set(); thread.join(3)
            self.assertEqual(len(failures), 1)
            self.assertIn("Wait for the active", str(failures[0]))
            self.assertEqual(h.manager.snapshot()["plan"]["repo"]["id"], REPO)
        finally:
            release.set(); thread.join(3)

