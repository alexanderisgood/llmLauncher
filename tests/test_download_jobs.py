def directory_bytes(path):
    return sum(item.stat().st_size for item in path.rglob("*") if item.is_file()) if path.exists() else 0


def normalized(value, root):
    if isinstance(value, dict):
        return {key: ("<time>" if key in {"time", "updatedAt", "expiresAt"} else normalized(item, root))
                for key, item in value.items()}
    if isinstance(value, list):
        return [normalized(item, root) for item in value]
    return value.replace(str(root), "<root>") if isinstance(value, str) else value


class Harness:
    def __init__(self, root, kind, *, frozen=False):
        self.root, self.kind, self.frozen = root, kind, frozen
        self.destination = root / "models/fixture/Generated"
        self.script = root / "downloader.py"; self.script.write_text(DOWNLOADER)
        self.mode = "complete"
        self.id = "fixture-acquisition"
        self.can_start = True
        self.launcher_phase = "idle"
        self.benchmark_running = False
        self.fetches = 0
        self.stack = ExitStack()
        self.files = [{"path":"artifact.gguf", "size":len(ARTIFACT), "role":"weight",
                       "sha256":hashlib.sha256(ARTIFACT).hexdigest()}]
        self.process_policy = jobs.ProcessPolicy(poll_seconds=.01, terminate_seconds=.5,
            kill_seconds=.5, cancel_join_seconds=.05)
        self.run = mock.Mock(); self.run.snapshot.side_effect = lambda: {"phase":self.launcher_phase}
        self.benchmark = mock.Mock(); self.benchmark.is_active.side_effect = lambda: self.benchmark_running
        if kind == "setup":
            policy = jobs.SetupPolicy(root / "state", REPO, len(ARTIFACT), "generated bytes", self.process_policy)
            services = jobs.SetupServices(self.setup_plan, self.argv, directory_bytes, self.verify_draft,
                lambda:self.launcher_phase == "idle", lambda:self.benchmark_running, launcher.LaunchCancelled)
            if frozen:
                self.stack.enter_context(mock.patch.multiple(legacy, STATE_DIR=policy.state_dir,
                    DFLASH2_DRAFT_REPO=REPO, DFLASH2_DRAFT_BYTES=len(ARTIFACT), DFLASH2_DRAFT_SIZE_LABEL="generated bytes",
                    validated_setup_request=self.setup_plan, build_dflash2_download_argv=self.argv,
                    directory_size=directory_bytes,
                    weight_completeness=lambda path,_config:(*self.verify_draft(path),len(ARTIFACT)),
                    dflash2_draft_complete=lambda path,_config:self.verify_draft(path)[0]))
                self.manager = legacy.SetupManager(self.run, self.benchmark)
            else:
                self.manager = jobs.SetupManager(policy, services)
        else:
            policy = jobs.AcquisitionPolicy(root / "state", 60, 1, ".fixture-acquisition.json", self.process_policy)
            services = jobs.AcquisitionServices(launcher.validated_hf_repo_id, launcher.validated_hf_revision,
                self.fetch, self.acquisition_plan, self.argv, launcher._hf_public_environment,
                launcher._acquisition_present_bytes, launcher._acquisition_safe_child, launcher.atomic_json,
                launcher.verify_model_acquisition, lambda:self.launcher_phase == "idle",
                lambda:self.benchmark_running, launcher.LaunchCancelled)
            if frozen:
                self.stack.enter_context(mock.patch.multiple(legacy, STATE_DIR=policy.state_dir,
                    MODEL_ACQUISITION_PLAN_TTL_SECONDS=60, MODEL_ACQUISITION_SCHEMA_VERSION=1,
                    MODEL_ACQUISITION_MARKER=policy.marker_name, fetch_model_acquisition_snapshot=self.fetch,
                    build_model_acquisition_plan=self.acquisition_plan, build_model_acquisition_download_argv=self.argv))
                self.manager = legacy.ModelAcquisitionManager(self.run, self.benchmark)
            else:
                self.manager = jobs.ModelAcquisitionManager(policy, services)

    def setup_plan(self, _payload, _models):
        return {}, {"id":"fixture-setup", "runtime":{"supported":True}, "ready":False,
            "draft":{"destination":str(self.destination), "repo":REPO, "revision":PIN,
                     "canDownload":self.can_start, "complete":False, "detail":"Generated admission blocked",
                     "existingBytes":directory_bytes(self.destination)}}

    def acquisition_plan(self, snapshot, _destination, _variant):
        return {"id":self.id, "confirmation":REPO + "@" + PIN, "canStart":self.can_start,
            "checks":[{"state":"blocked", "detail":"Generated admission blocked"}] if not self.can_start else [],
            "repo":{"id":snapshot["repoId"], "pinnedRevision":snapshot["pinnedRevision"]},
            "destination":{"path":str(self.destination), "existingBytes":launcher._acquisition_present_bytes(self.destination,self.files)},
            "selection":{"id":"generated-gguf", "format":"gguf", "files":copy.deepcopy(self.files),
                         "fileCount":1, "sizeBytes":len(ARTIFACT)}, "action":"download"}

    def fetch(self, repo, _revision):
        self.fetches += 1
        return {"repoId":repo, "pinnedRevision":PIN}

    def argv(self, _plan):
        return [sys.executable, str(self.script), str(self.destination), self.mode]

    def verify_draft(self, destination):
        valid = (destination / "artifact.gguf").read_bytes() == ARTIFACT
        return valid, "complete" if valid else "generated bytes mismatch"

    def approve(self):
        if self.kind == "setup":
            return {"modelId":"generated", "confirmation":REPO}
        plan = self.manager.inspect({"repoId":REPO, "revision":"main", "destination":"generated"})
        return {"planId":plan["id"], "confirmation":plan["confirmation"], "licenseReviewed":True}

    def start(self, payload=None):
        payload = self.approve() if payload is None else payload
        return self.manager.start(payload, []) if self.kind == "setup" else self.manager.start(payload)

    def wait(self, timeout=5):
        deadline = time.monotonic() + timeout
        while self.manager.is_active() and time.monotonic() < deadline:
            time.sleep(.01)
        if self.manager.is_active():
            raise AssertionError("Generated job did not finish")
        return self.manager.snapshot()

    def close(self):
        try:
            self.manager.cancel()
            if self.manager.thread is not None:
                self.manager.thread.join(3)
            if self.manager.process is not None:
                jobs.terminate_owned_downloader(self.manager.process, self.process_policy)
        finally:
            self.stack.close()


class DownloadJobTests(unittest.TestCase):
    def fixture(self, kind, *, frozen=False):
        temporary = tempfile.TemporaryDirectory(prefix="generated-download-job-")
        harness = Harness(Path(temporary.name).resolve(), kind, frozen=frozen)
        self.addCleanup(temporary.cleanup); self.addCleanup(harness.close)
        return harness

    def wait_for(self, predicate, timeout=3):
        deadline = time.monotonic() + timeout
        while not predicate() and time.monotonic() < deadline:
            time.sleep(.01)
        self.assertTrue(predicate())

    def test_module_boundary_and_policies_are_independent_and_immutable(self):
        self.assertNotIn("import launcher", Path(jobs.__file__).read_text())
        fixture = Path(__file__).parent / "fixtures/download_jobs_legacy.py"
        manifest = json.loads(fixture.with_suffix(".json").read_text())
        self.assertEqual(hashlib.sha256(fixture.read_bytes()).hexdigest(), manifest["fixtureSha256"])
        h = self.fixture("setup")
        with self.assertRaises(FrozenInstanceError):
            h.manager.policy.draft_repo = "changed"
        with self.assertRaises(FrozenInstanceError):
            h.manager.services.download_argv = lambda _:[]

    def test_completed_and_failed_public_contract_matches_frozen_managers(self):
        for kind in ("setup", "acquisition"):
            for mode in ("complete", "fail", "corrupt"):
                with self.subTest(kind=kind, mode=mode):
                    states = []
                    markers = []
                    for frozen in (True, False):
                        h = self.fixture(kind, frozen=frozen); h.mode = mode
                        h.start(); state = h.wait()
                        states.append(normalized(state, h.root))
                        marker = h.destination / ".fixture-acquisition.json"
                        if marker.exists():
                            markers.append(normalized(json.loads(marker.read_text()), h.root))
                        h.close()
                    self.assertEqual(states[0], states[1])
                    if markers:
                        self.assertEqual(markers[0], markers[1])

    def test_missing_confirmation_license_idle_and_resource_guards_match(self):
        for kind in ("setup", "acquisition"):
            for condition in ("confirmation", "license", "launcher", "benchmark", "resource"):
                if condition == "license" and kind == "setup":
                    continue
                with self.subTest(kind=kind, condition=condition):
                    errors = []
                    for frozen in (True, False):
                        h = self.fixture(kind, frozen=frozen); payload = h.approve()
                        if condition == "confirmation": payload["confirmation"] = "wrong"
                        if condition == "license": payload["licenseReviewed"] = False
                        if condition == "launcher": h.launcher_phase = "running"
                        if condition == "benchmark": h.benchmark_running = True
                        if condition == "resource": h.can_start = False
                        with self.assertRaises(ValueError) as failure:
                            h.start(payload)
                        errors.append(str(failure.exception))
                        self.assertEqual(h.manager.snapshot()["phase"], "idle")
                        self.assertFalse(h.destination.exists())
                        h.close()
                    self.assertEqual(errors[0], errors[1])

    def test_inspection_cache_expiry_and_pinned_identity_match(self):
        for frozen in (True, False):
            with self.subTest(frozen=frozen):
                h = self.fixture("acquisition", frozen=frozen)
                with mock.patch.object(time, "time", return_value=100):
                    payload = h.approve(); h.approve()
                self.assertEqual(h.fetches, 1)
                h.id = "changed-identity"
                with mock.patch.object(time, "time", return_value=101), self.assertRaisesRegex(ValueError, "identity changed"):
                    h.start(payload)
                with mock.patch.object(time, "time", return_value=161), self.assertRaisesRegex(ValueError, "expired or changed"):
                    h.start(payload)
