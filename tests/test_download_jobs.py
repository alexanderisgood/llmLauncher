            h.start(); failed = h.wait()
            self.assertEqual(failed["phase"], "failed")
            self.assertFalse(failed["plan"]["draft"]["complete"])
            pairing.assert_called_once_with(h.destination, {"fixture":True})
            pairing.return_value = True
            h.start(); self.assertEqual(h.wait()["phase"], "completed")


